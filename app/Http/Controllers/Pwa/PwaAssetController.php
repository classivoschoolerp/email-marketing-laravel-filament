<?php

declare(strict_types=1);

namespace App\Http\Controllers\Pwa;

use App\Services\Branding\BrandContext;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Response;
use Throwable;

/**
 * Serves the two §4.8 F-4.8-002 PWA documents (WP-40).
 *
 * Both are ROUTES rather than files in public/ because both must be
 * localised (`__()` — no hardcoded English, docs/ARCHITECTURE.md) and branded (§6.4
 * multi-domain: two brands on one install must not advertise the same app
 * name or icon). The service worker still resolves at the site root, so its
 * registration scope is `/` exactly as a static file's would be.
 */
class PwaAssetController
{
    /** The web app manifest (F-4.8-002 "install"). */
    public function manifest(): JsonResponse
    {
        [$name, $icon, $color] = $this->brand();

        $icons = [];

        if ($icon !== null) {
            // `purpose: any` only — a logo is not guaranteed to survive the
            // maskable safe-zone crop, and claiming otherwise produces a
            // clipped icon on Android.
            $icons[] = ['src' => $icon, 'sizes' => 'any', 'type' => 'image/png', 'purpose' => 'any'];
        }

        $icons[] = ['src' => asset('favicon.ico'), 'sizes' => '48x48', 'type' => 'image/x-icon', 'purpose' => 'any'];

        return response()->json([
            'id' => '/',
            'name' => $name,
            'short_name' => __('analytics.pwa.short_name'),
            'description' => __('analytics.pwa.description'),
            'start_url' => url('/customer'),
            'scope' => url('/'),
            'display' => 'standalone',
            'orientation' => 'any',
            'background_color' => '#ffffff',
            'theme_color' => $color,
            'lang' => str_replace('_', '-', app()->getLocale()),
            'dir' => 'auto',
            'icons' => $icons,
            'shortcuts' => [
                [
                    'name' => __('analytics.page.navigation_label'),
                    'url' => url('/customer/analytics'),
                ],
                [
                    'name' => __('campaigns.resource.navigation_group'),
                    'url' => url('/customer/campaigns'),
                ],
            ],
        ], 200, [
            'Content-Type' => 'application/manifest+json',
            'Cache-Control' => 'public, max-age=3600',
        ]);
    }

    /**
     * The service worker (F-4.8-002 "offline shell").
     *
     * SECURITY: it caches STATIC assets and the offline shell only. Every
     * navigation is network-first and its response is NEVER written to the
     * cache, so no authenticated page — no subscriber list, no campaign
     * report — can ever be left on a shared or lost device. The allow-list
     * in `isCacheableAsset` is the single place that decides what may be
     * stored.
     */
    public function serviceWorker(): Response
    {
        // Cache name is version-stamped so an upgrade evicts the old shell
        // (the `activate` handler below deletes every other cache key).
        $version = preg_replace('/[^A-Za-z0-9._-]/', '', (string) config('emp.core_version', '1.0.0')) ?: '1';
        $offline = url('/offline');
        $scope = rtrim(url('/'), '/');

        $script = <<<JS
        /* §4.8 F-4.8-002 service worker (WP-40). Generated by PwaAssetController. */
        const CACHE = 'emp-shell-v{$version}';
        const OFFLINE_URL = '{$offline}';
        const ORIGIN = '{$scope}';

        /* Only these prefixes may ever be written to the cache. Everything
           else — every panel page, every API call — is network-only. */
        const ASSET_PREFIXES = ['/build/', '/css/', '/js/', '/images/', '/favicon.ico'];

        /* Never touched by the worker at all. */
        const NEVER = ['/api/', '/livewire/', '/admin-downloads/', '/track/', '/broadcasting/'];

        function isAsset(url) {
            return ASSET_PREFIXES.some((prefix) => url.pathname.startsWith(prefix));
        }

        function isExcluded(url) {
            return NEVER.some((prefix) => url.pathname.startsWith(prefix));
        }

        self.addEventListener('install', (event) => {
            event.waitUntil(
                caches.open(CACHE)
                    .then((cache) => cache.addAll([OFFLINE_URL]))
                    .then(() => self.skipWaiting())
            );
        });

        self.addEventListener('activate', (event) => {
            event.waitUntil(
                caches.keys()
                    .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
                    .then(() => self.clients.claim())
            );
        });

        self.addEventListener('fetch', (event) => {
            const request = event.request;

            if (request.method !== 'GET') {
                return;
            }

            const url = new URL(request.url);

            if (url.origin !== ORIGIN || isExcluded(url)) {
                return;
            }

            /* Navigations: network first, offline shell as the fallback.
               The response is deliberately NOT cached — it may contain
               account data. */
            if (request.mode === 'navigate') {
                event.respondWith(
                    fetch(request).catch(() => caches.match(OFFLINE_URL))
                );

                return;
            }

            /* Static build output only: cache-first, then fill the cache. */
            if (isAsset(url)) {
                event.respondWith(
                    caches.match(request).then((hit) => hit || fetch(request).then((response) => {
                        if (response && response.status === 200 && response.type === 'basic') {
                            const copy = response.clone();
                            caches.open(CACHE).then((cache) => cache.put(request, copy));
                        }

                        return response;
                    }))
                );
            }
        });
        JS;

        return response($script, 200, [
            'Content-Type' => 'application/javascript; charset=UTF-8',
            'Service-Worker-Allowed' => '/',
            'Cache-Control' => 'no-cache',
        ]);
    }

    /**
     * Brand name / icon / colour for the manifest. Falls back to the app name
     * when the §6.4 brand context cannot resolve (installer, pre-migration).
     *
     * @return array{0: string, 1: ?string, 2: string}
     */
    private function brand(): array
    {
        try {
            $brand = app(BrandContext::class)->current();

            return [
                $brand->name !== '' ? $brand->name : (string) config('app.name'),
                $brand->logoUrl(),
                '#0f172a',
            ];
        } catch (Throwable) {
            return [(string) config('app.name', __('analytics.pwa.name')), null, '#0f172a'];
        }
    }
}
