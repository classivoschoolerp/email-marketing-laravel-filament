<?php

declare(strict_types=1);

namespace App\Sending\Drivers;

use App\Models\DeliveryServer;
use App\Sending\Message;
use App\Sending\SendResult;
use Illuminate\Support\Str;
use Throwable;

/**
 * Pickup-directory / SMTP-pickup driver (spec §2.9.2 F-2.9.2-015, D-21 key
 * "pickup-directory"). Spools the full RFC 2822/5322 message (Symfony MIME,
 * incl. Force-FROM/REPLY-TO, custom headers and DKIM) as a .eml file into
 * config.pickup_path for a local MTA (IIS SMTP pickup, msmtp watcher, ...)
 * to deliver. utf8mb4 subjects/bodies (CJK + emoji, spec §0.1) survive via
 * RFC 2047/quoted-printable encoding — covered by the round-trip test.
 *
 * The file is written to a .tmp name first and renamed, so a pickup daemon
 * never reads a half-written message.
 *
 * Transient-vs-permanent classification:
 *  | condition                              | classification |
 *  |----------------------------------------|----------------|
 *  | directory missing/not writable, write  | transient      |
 *  |   or rename failure (disk full, perms) | transient      |
 *  | message build error / no pickup_path   | permanent      |
 */
class PickupDirectoryDriver extends AbstractDriver
{
    public function key(): string
    {
        return 'pickup-directory';
    }

    public function pickupPath(DeliveryServer $server): string
    {
        return (string) $server->configValue('pickup_path', '');
    }

    public function send(Message $message, DeliveryServer $server): SendResult
    {
        if (($errors = $this->validateConfig($server)) !== []) {
            return SendResult::permanentFailure(implode(' ', $errors));
        }

        try {
            $raw = $this->mime->build($message, $server)->toString();
        } catch (Throwable $e) {
            return SendResult::permanentFailure($e->getMessage());
        }

        $dir = rtrim($this->pickupPath($server), '/\\');

        try {
            if (! is_dir($dir) && ! @mkdir($dir, 0775, true) && ! is_dir($dir)) {
                return SendResult::transientFailure(__('sending.errors.pickup_dir_unavailable', ['dir' => $dir]));
            }

            $name = now()->format('YmdHis').'-'.Str::uuid();
            $tmp = $dir.DIRECTORY_SEPARATOR.$name.'.tmp';
            $final = $dir.DIRECTORY_SEPARATOR.$name.'.eml';

            if (@file_put_contents($tmp, $raw) === false || ! @rename($tmp, $final)) {
                @unlink($tmp);

                return SendResult::transientFailure(__('sending.errors.pickup_write_failed', ['dir' => $dir]));
            }

            return SendResult::success($this->extractMessageId($raw) ?? $name.'.eml');
        } catch (Throwable $e) {
            return SendResult::transientFailure($e->getMessage());
        }
    }

    /** Message-ID generated by Symfony during toString(), if present. */
    private function extractMessageId(string $raw): ?string
    {
        return preg_match('/^Message-ID:\s*<([^>]+)>/mi', $raw, $m) === 1 ? $m[1] : null;
    }

    public function validateConfig(DeliveryServer $server): array
    {
        return $this->pickupPath($server) === ''
            ? ['config.pickup_path' => __('sending.validation.pickup_path_required')]
            : [];
    }

    public function capabilities(): array
    {
        return [
            'transport' => 'pickup',
            'attachments' => true,
            'custom_headers' => true,
            'dkim' => true,
        ];
    }

    public function formSchema(): array
    {
        return [
            $this->field('config.pickup_path', 'text', [
                'required' => true,
                'help' => 'sending.help.pickup_path',
            ]),
        ];
    }
}
