<?php

declare(strict_types=1);

namespace App\Policies;

use App\Models\User;
use App\Models\UserRecoveryCode;
/**
 * Admin 2FA recovery codes are managed exclusively through the admin
 * Security page flows; a user may only ever touch their own codes (D-35 —
 * mirrors CustomerRecoveryCodePolicy).
 */
use App\Policies\Concerns\DeniesNonAdminActors;

class UserRecoveryCodePolicy
{
    use DeniesNonAdminActors;

    public function viewAny(User $user): bool
    {
        return true; // scoped to their own rows by the Security page query
    }

    public function view(User $user, UserRecoveryCode $code): bool
    {
        return (int) $code->user_id === (int) $user->getKey();
    }

    public function create(User $user): bool
    {
        return false; // generated by TwoFactorService only
    }

    public function update(User $user, UserRecoveryCode $code): bool
    {
        return false;
    }

    public function delete(User $user, UserRecoveryCode $code): bool
    {
        return false;
    }
}
