<?php

declare(strict_types=1);

namespace App\Policies;

use App\Models\Customer;
use App\Models\CustomerRecoveryCode;

/**
 * Recovery codes are managed exclusively through the Security page flows; a
 * customer may only ever touch their own codes (spec §2.15.2).
 */
class CustomerRecoveryCodePolicy
{
    public function viewAny(Customer $customer): bool
    {
        return true; // scoped to their own rows by the Security page query
    }

    public function view(Customer $customer, CustomerRecoveryCode $code): bool
    {
        return (int) $code->customer_id === (int) $customer->getKey();
    }

    public function create(Customer $customer): bool
    {
        return false; // generated by TwoFactorService only
    }

    public function update(Customer $customer, CustomerRecoveryCode $code): bool
    {
        return false;
    }

    public function delete(Customer $customer, CustomerRecoveryCode $code): bool
    {
        return false;
    }
}
